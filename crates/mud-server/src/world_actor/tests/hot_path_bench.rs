//! Manual hot-path measurement for the world actor.
//!
//! Run with:
//! `cargo test -p tiamud-server --release --locked hot_path_measurement -- --ignored --nocapture`
//!
//! Every scenario runs against three backends in turn:
//!
//! - `memory`: the in-memory test adapter. It serializes exactly the JSON a
//!   SQL adapter would write (character gameplay/identity, the sectioned
//!   runtime head, manifest and rewritten sections of schema v17, and events),
//!   so its `payload` bytes are the per-commit payload, while its times
//!   exclude SQL I/O.
//! - `sqlite`: the production `SqliteCharacterStore` on a file in a temporary
//!   directory (`TIAMUD_BENCH_DIR`, else the system temporary directory) with
//!   the production pragmas (WAL, `synchronous = FULL`).
//! - `postgres`: the production `PostgresCharacterStore` in a fresh schema of
//!   the disposable database named by `TIAMUD_TEST_POSTGRES_URL` (skipped when
//!   unset). The schema is dropped afterwards.
//!
//! Each store is wrapped in the production `MeasuredCharacterStore`, so
//! `commit` is the wall time of the write transactions issued while one
//! action ran (including the bounded queue hop to the backend owner thread),
//! and `actor` is the end-to-end time of the actor apply/tick path.
//! `stored` is what the latest runtime write left at its manifest revision
//! (head + manifest + rewritten section rows, in bytes) and, on PostgreSQL,
//! `wal` is the WAL generated by the action (`pg_current_wal_lsn` delta,
//! after TOAST compression). Numbers are local and diagnostic, not CI
//! evidence.

use super::*;
use crate::operations::RuntimeMetrics;
use crate::persistence::{MeasuredCharacterStore, SqliteCharacterStore};
use crate::persistence_postgres::PostgresCharacterStore;
use std::sync::Arc;
use tiamud_core::{RuntimeItemInstanceSnapshot, RuntimeItemLocation};

const TICKS: usize = 60;
const COMMANDS: usize = 100;

struct BenchWorld {
    world: World,
    sessions: Vec<SessionId>,
    mover: SessionId,
    route: (Direction, Direction),
    /// Name of the plain prototype placed in every room, for take/drop.
    item_name: String,
}

/// A short alphabetic name so every backend accepts it.
fn bench_name(index: usize) -> String {
    let mut suffix = String::new();
    let mut value = index;
    for _ in 0..3 {
        suffix.insert(0, char::from(b'a' + (value % 26) as u8));
        value /= 26;
    }
    format!("Bench{suffix}")
}

async fn bench_world(
    store: &dyn CharacterStore,
    characters: usize,
    staged_items: usize,
    items_per_room: usize,
    carried_per_character: usize,
) -> BenchWorld {
    let loaded = crate::world_loader::default_loaded_world().unwrap();
    let mut world = crate::world_loader::build_loaded_world(&loaded).unwrap();
    let rooms = loaded
        .definition
        .rooms
        .iter()
        .map(|room| room.stable_id.clone())
        .collect::<Vec<_>>();
    // Find a two-way route for the moving session.
    let mut route = None;
    'outer: for room in &loaded.definition.rooms {
        for exit in &room.exits {
            if let Some(target) = loaded
                .definition
                .rooms
                .iter()
                .find(|candidate| candidate.stable_id == exit.target_room_id)
                && let Some(back) = target
                    .exits
                    .iter()
                    .find(|back| back.target_room_id == room.stable_id)
            {
                route = Some((room.stable_id.clone(), exit.direction, back.direction));
                break 'outer;
            }
        }
    }
    let (route_room, there, back) = route.expect("default world has a two-way exit");
    let prototype_definition = loaded
        .definition
        .item_prototypes
        .iter()
        .find(|prototype| {
            prototype.container.is_none()
                && prototype.sealed_loot_table_id.is_none()
                && prototype.transfer_policy == ItemTransferPolicy::Transferable
        })
        .expect("default world has a plain transferable prototype");
    let prototype = prototype_definition.prototype_id.clone();
    // A second plain prototype with a distinct name: exactly one instance of
    // it lies in the mover's room, so take/drop resolve unambiguously.
    let initial = world.runtime_snapshot();
    let movable = loaded
        .definition
        .item_prototypes
        .iter()
        .find(|candidate| {
            candidate.container.is_none()
                && candidate.sealed_loot_table_id.is_none()
                && candidate.transfer_policy == ItemTransferPolicy::Transferable
                && candidate.name != prototype_definition.name
                && !initial
                    .item_instances
                    .values()
                    .any(|instance| instance.prototype_id == candidate.prototype_id)
        })
        .expect("default world has an unplaced plain transferable prototype");
    let movable_prototype = movable.prototype_id.clone();
    let item_name = movable.name.clone();

    // Durable identities first: SQL stores only accept commits for
    // characters they know.
    let mut snapshots = Vec::new();
    for character in 0..characters {
        let room = if character == 0 {
            route_room.clone()
        } else {
            rooms[character % rooms.len()].clone()
        };
        let name = bench_name(character);
        let account = store.load_or_create_account(&name).await.unwrap();
        let snapshot = store
            .load_or_create_character_with_gameplay(
                account.id,
                &name,
                &room,
                CharacterGameplaySnapshot::default(),
            )
            .await
            .unwrap();
        snapshots.push(snapshot);
    }

    let mut snapshot = world.runtime_snapshot();
    let mut sequence = snapshot.next_item_instance_sequence;
    let mut add_item = |snapshot: &mut WorldRuntimeSnapshot, location: RuntimeItemLocation| {
        let id = ItemInstanceId(format!("runtime:{sequence}"));
        sequence += 1;
        snapshot.item_instances.insert(
            id.clone(),
            RuntimeItemInstanceSnapshot {
                prototype_id: prototype.clone(),
                location,
                binding: tiamud_core::ItemBinding::Unbound,
                item_affixes: Vec::new(),
            },
        );
        snapshot.item_provenance.insert(
            id,
            tiamud_core::ItemProvenance::RuntimeCreated { created_tick: 0 },
        );
    };
    // Staged instances model a large world whose items are mostly out of
    // every player's sight: they cost nothing to render but every former
    // full scan walked them.
    for _ in 0..staged_items {
        add_item(&mut snapshot, RuntimeItemLocation::Staged);
    }
    for room in &rooms {
        for _ in 0..items_per_room {
            add_item(
                &mut snapshot,
                RuntimeItemLocation::Room {
                    room_id: room.clone(),
                },
            );
        }
    }
    for character in &snapshots {
        for _ in 0..carried_per_character {
            add_item(
                &mut snapshot,
                RuntimeItemLocation::Carried {
                    character_id: character.id,
                },
            );
        }
    }
    let movable_id = ItemInstanceId(format!("runtime:{sequence}"));
    sequence += 1;
    snapshot.item_instances.insert(
        movable_id.clone(),
        RuntimeItemInstanceSnapshot {
            prototype_id: movable_prototype,
            location: RuntimeItemLocation::Room {
                room_id: route_room.clone(),
            },
            binding: tiamud_core::ItemBinding::Unbound,
            item_affixes: Vec::new(),
        },
    );
    snapshot.item_provenance.insert(
        movable_id,
        tiamud_core::ItemProvenance::RuntimeCreated { created_tick: 0 },
    );
    snapshot.next_item_instance_sequence = sequence;
    world.restore_runtime_snapshot(snapshot).unwrap();

    let mut sessions = Vec::new();
    for (index, character) in snapshots.into_iter().enumerate() {
        let session = SessionId(1_000 + index as u64);
        world.connect(session, character).unwrap();
        sessions.push(session);
    }
    BenchWorld {
        world,
        mover: sessions[0],
        sessions,
        route: (there, back),
        item_name,
    }
}

/// Observes what one action left in the backend, outside the timed window.
enum Probe {
    Memory(Arc<MemoryStore>),
    Sqlite {
        connection: rusqlite::Connection,
        last_revision: i64,
    },
    Postgres {
        client: Arc<std::sync::Mutex<postgres::Client>>,
        last_revision: i64,
    },
}

#[derive(Clone, Copy, Default)]
struct Observed {
    /// Memory: serialized payload of every commit. SQL: unused.
    payload: u64,
    /// Bytes the latest runtime write stored (head + manifest + sections).
    stored: u64,
    sections: u64,
    /// PostgreSQL WAL generated, in bytes.
    wal: u64,
}

impl Probe {
    async fn mark(&mut self) -> u64 {
        match self {
            Probe::Memory(store) => store.bytes_written.load(Ordering::SeqCst) as u64,
            Probe::Sqlite { .. } => 0,
            Probe::Postgres { client, .. } => {
                let client = client.clone();
                tokio::task::spawn_blocking(move || {
                    let row = client
                        .lock()
                        .unwrap()
                        .query_one(
                            "SELECT pg_wal_lsn_diff(pg_current_wal_lsn(), '0/0')::BIGINT",
                            &[],
                        )
                        .unwrap();
                    row.get::<_, i64>(0) as u64
                })
                .await
                .unwrap()
            }
        }
    }

    async fn observe(&mut self, mark: u64) -> Observed {
        match self {
            Probe::Memory(store) => Observed {
                payload: store.bytes_written.load(Ordering::SeqCst) as u64 - mark,
                ..Observed::default()
            },
            Probe::Sqlite {
                connection,
                last_revision,
            } => {
                let (revision, head): (i64, i64) = connection
                    .query_row(
                        "SELECT CAST(json_extract(manifest_json, '$.revision') AS INTEGER),
                                length(CAST(head_json AS BLOB))
                                  + length(CAST(manifest_json AS BLOB))
                         FROM world_runtime WHERE singleton = 1",
                        [],
                        |row| Ok((row.get(0)?, row.get(1)?)),
                    )
                    .unwrap();
                if revision == *last_revision {
                    return Observed::default();
                }
                *last_revision = revision;
                let (sections, bytes): (i64, i64) = connection
                    .query_row(
                        "SELECT COUNT(*), COALESCE(SUM(length(CAST(section_json AS BLOB))), 0)
                         FROM world_runtime_sections WHERE revision = ?1",
                        [revision],
                        |row| Ok((row.get(0)?, row.get(1)?)),
                    )
                    .unwrap();
                Observed {
                    stored: (head + bytes) as u64,
                    sections: sections as u64,
                    ..Observed::default()
                }
            }
            Probe::Postgres {
                client,
                last_revision,
            } => {
                let shared = client.clone();
                let previous = *last_revision;
                let (revision, observed) = tokio::task::spawn_blocking(move || {
                    let mut client = shared.lock().unwrap();
                    let wal: i64 = client
                        .query_one(
                            "SELECT pg_wal_lsn_diff(pg_current_wal_lsn(), '0/0')::BIGINT",
                            &[],
                        )
                        .unwrap()
                        .get(0);
                    let wal = (wal as u64).saturating_sub(mark);
                    let row = client
                        .query_one(
                            "SELECT (manifest_json::jsonb ->> 'revision')::BIGINT,
                                    (octet_length(head_json) + octet_length(manifest_json))::BIGINT
                             FROM world_runtime WHERE singleton = 1",
                            &[],
                        )
                        .unwrap();
                    let revision: i64 = row.get(0);
                    if revision == previous {
                        return (
                            revision,
                            Observed {
                                wal,
                                ..Observed::default()
                            },
                        );
                    }
                    let head: i64 = row.get(1);
                    let row = client
                        .query_one(
                            "SELECT COUNT(*)::BIGINT,
                                    COALESCE(SUM(octet_length(section_json)), 0)::BIGINT
                             FROM world_runtime_sections WHERE revision = $1",
                            &[&revision],
                        )
                        .unwrap();
                    let sections: i64 = row.get(0);
                    let bytes: i64 = row.get(1);
                    (
                        revision,
                        Observed {
                            stored: (head + bytes) as u64,
                            sections: sections as u64,
                            wal,
                            ..Observed::default()
                        },
                    )
                })
                .await
                .unwrap();
                *last_revision = revision;
                observed
            }
        }
    }
}

/// Samples of one kind of action.
#[derive(Default)]
struct Samples {
    actor_us: Vec<u64>,
    /// Commit wall time, only for actions that issued a write transaction.
    commit_us: Vec<u64>,
    transactions: u64,
    payload: u64,
    stored: u64,
    sections: u64,
    wal: u64,
    runtime_writes: u64,
}

impl Samples {
    fn record(&mut self, actor: Duration, transactions: u64, commit_us: u64, observed: Observed) {
        self.actor_us.push(actor.as_micros() as u64);
        if transactions > 0 {
            self.commit_us.push(commit_us);
        }
        self.transactions += transactions;
        self.payload += observed.payload;
        self.stored += observed.stored;
        self.sections += observed.sections;
        self.wal += observed.wal;
        if observed.stored > 0 {
            self.runtime_writes += 1;
        }
    }

    fn summary(&self, label: &str) -> String {
        let commits = self.commit_us.len().max(1) as u64;
        format!(
            "{label}: actor p50={:.3}ms p95={:.3}ms | commit p50={:.3}ms p95={:.3}ms \
             max={:.3}ms ({}/{} actions committed, {} tx) | payload/commit={}B \
             stored/commit={}B sections/runtime-write={:.2} wal/commit={}B",
            percentile_ms(&self.actor_us, 0.50),
            percentile_ms(&self.actor_us, 0.95),
            percentile_ms(&self.commit_us, 0.50),
            percentile_ms(&self.commit_us, 0.95),
            percentile_ms(&self.commit_us, 1.0),
            self.commit_us.len(),
            self.actor_us.len(),
            self.transactions,
            self.payload / commits,
            self.stored / commits,
            self.sections as f64 / self.runtime_writes.max(1) as f64,
            self.wal / commits,
        )
    }
}

/// Nearest-rank percentile in milliseconds.
fn percentile_ms(samples: &[u64], quantile: f64) -> f64 {
    if samples.is_empty() {
        return 0.0;
    }
    let mut sorted = samples.to_vec();
    sorted.sort_unstable();
    let rank = ((quantile * sorted.len() as f64).ceil() as usize).clamp(1, sorted.len());
    sorted[rank - 1] as f64 / 1_000.0
}

async fn run_scenario(
    backend: &str,
    inner: Arc<dyn CharacterStore>,
    mut probe: Probe,
    characters: usize,
) {
    let metrics = Arc::new(RuntimeMetrics::default());
    let store = MeasuredCharacterStore::new(inner, metrics.clone());
    let BenchWorld {
        mut world,
        sessions,
        mover,
        route,
        item_name,
    } = bench_world(&store, characters, 5_000, 5, 10).await;
    let roles = sessions
        .iter()
        .map(|session| (*session, AccountRole::Player))
        .collect::<HashMap<_, _>>();
    let content = RuntimeContent::default();
    let mut delivery = DeliveryRouter::new(None);
    let mut inboxes = sessions
        .iter()
        .map(|session| delivery.register(*session))
        .collect::<Vec<_>>();
    let drain = |inboxes: &mut Vec<crate::delivery::DeliveryInbox>| {
        for inbox in inboxes.iter_mut() {
            while inbox.try_recv().is_ok() {}
        }
    };

    // Warm up: one full commit so later ticks start from a durable state.
    let mark = probe.mark().await;
    assert!(persist_tick(&mut world, &content, &roles, &store, &mut delivery).await);
    drain(&mut inboxes);
    let warmup = probe.observe(mark).await;

    // --- Ticks -----------------------------------------------------------
    let mut ticks = Samples::default();
    for _ in 0..TICKS {
        let (tx_before, us_before) = metrics.database_transaction_totals();
        let mark = probe.mark().await;
        let started = Instant::now();
        assert!(persist_tick(&mut world, &content, &roles, &store, &mut delivery).await);
        let elapsed = started.elapsed();
        let (tx_after, us_after) = metrics.database_transaction_totals();
        let observed = probe.observe(mark).await;
        ticks.record(
            elapsed,
            tx_after - tx_before,
            us_after - us_before,
            observed,
        );
        drain(&mut inboxes);
    }

    // --- Commands (full actor apply path, durable commit included) --------
    let mut social = SocialRuntime::new();
    let mut command_roles = roles.clone();
    let mut staff = HashMap::new();
    let mut moves = Samples::default();
    let mut items = Samples::default();
    for index in 0..2 * COMMANDS {
        // Interleave take, drop, there, back so both kinds see the same
        // backend state (WAL size, checkpoints, autovacuum) over the run and
        // the item always lies in the mover's room when taken.
        let item_command = index % 4 < 2;
        let selection = tiamud_core::ItemSelection::one(item_name.clone());
        let action = match index % 4 {
            0 => PlayerAction::Take(selection),
            1 => PlayerAction::Drop(selection),
            2 => PlayerAction::Move(route.0),
            _ => PlayerAction::Move(route.1),
        };
        let (tx_before, us_before) = metrics.database_transaction_totals();
        let mark = probe.mark().await;
        let started = Instant::now();
        apply(
            ApplyResources {
                world: &mut world,
                runtime_content: &content,
                social: &mut social,
                store: &store,
                session_roles: &mut command_roles,
                session_staff_accesses: &mut staff,
                delivery: &mut delivery,
            },
            mover,
            AccountRole::Player,
            action,
        )
        .await
        .unwrap();
        let elapsed = started.elapsed();
        let (tx_after, us_after) = metrics.database_transaction_totals();
        let observed = probe.observe(mark).await;
        let samples = if item_command { &mut items } else { &mut moves };
        samples.record(
            elapsed,
            tx_after - tx_before,
            us_after - us_before,
            observed,
        );
        drain(&mut inboxes);
    }

    let snapshot = world.runtime_snapshot();
    let instances = snapshot.item_instances.len();
    let full_snapshot = serde_json::to_vec(&snapshot).unwrap().len();
    let item_section = serde_json::to_vec(&snapshot.item_instances).unwrap().len();
    println!(
        "HOTPATH backend={backend} characters={characters} items={instances} \
         full_snapshot_bytes={full_snapshot} itemInstances_bytes={item_section} \
         warmup_stored={}B warmup_wal={}B",
        warmup.stored, warmup.wal,
    );
    println!("  {}", ticks.summary("tick"));
    println!("  {}", moves.summary("move"));
    println!("  {}", items.summary("take/drop"));
    store.shutdown().await.unwrap();
}

fn bench_directory() -> tempfile::TempDir {
    match std::env::var_os("TIAMUD_BENCH_DIR") {
        Some(directory) => tempfile::TempDir::new_in(directory).unwrap(),
        None => tempfile::TempDir::new().unwrap(),
    }
}

#[tokio::test(flavor = "current_thread")]
#[ignore = "manual measurement; run with --ignored --nocapture in release"]
async fn hot_path_measurement() {
    let postgres_url = std::env::var("TIAMUD_TEST_POSTGRES_URL").ok();
    for characters in [50, 200] {
        // In-memory oracle for payload bytes.
        let memory = Arc::new(MemoryStore::default());
        // The per-commit assembly proof decodes the whole snapshot; it is a
        // test oracle, not part of what a SQL store does on the hot path.
        memory
            .skip_section_verification
            .store(true, Ordering::SeqCst);
        run_scenario("memory", memory.clone(), Probe::Memory(memory), characters).await;

        // File-backed SQLite with the production pragmas.
        let directory = bench_directory();
        let path = directory.path().join("hot-path.sqlite3");
        let sqlite = Arc::new(SqliteCharacterStore::open(&path).await.unwrap());
        let connection = rusqlite::Connection::open(&path).unwrap();
        run_scenario(
            "sqlite",
            sqlite,
            Probe::Sqlite {
                connection,
                last_revision: 0,
            },
            characters,
        )
        .await;
        drop(directory);

        // Disposable PostgreSQL, one fresh schema per scenario.
        if let Some(base_url) = &postgres_url {
            let nonce = std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos();
            let schema = format!("tiamud_hot_path_{}_{nonce}", std::process::id());
            let separator = if base_url.contains('?') { '&' } else { '?' };
            let scoped = format!("{base_url}{separator}options=-csearch_path%3D{schema}");
            let admin = {
                let base_url = base_url.clone();
                let schema = schema.clone();
                tokio::task::spawn_blocking(move || {
                    let mut client = tiamud_persistence_postgres::connect(&base_url).unwrap();
                    client
                        .batch_execute(&format!(
                            "CREATE SCHEMA {schema}; SET search_path TO {schema}"
                        ))
                        .unwrap();
                    Arc::new(std::sync::Mutex::new(client))
                })
                .await
                .unwrap()
            };
            let postgres = Arc::new(PostgresCharacterStore::open(&scoped).await.unwrap());
            run_scenario(
                "postgres",
                postgres,
                Probe::Postgres {
                    client: admin.clone(),
                    last_revision: 0,
                },
                characters,
            )
            .await;
            tokio::task::spawn_blocking(move || {
                admin
                    .lock()
                    .unwrap()
                    .batch_execute(&format!("DROP SCHEMA {schema} CASCADE"))
                    .unwrap();
            })
            .await
            .unwrap();
        }
    }
}
