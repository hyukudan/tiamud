//! Generates `apps/web/src/lib/generated/core.ts`, the TypeScript shape of
//! the perception-safe projections that `tiamud.v1` frames embed (scene,
//! player, item, map, narrative event and reward-odds views), and fails when
//! the committed file is stale.
//!
//! The `TS` derives are applied with `cfg_attr(test, ...)` and ts-rs is only a
//! dev-dependency, so neither enters the release dependency graph.
//!
//! Check (part of `cargo test --workspace`):
//!
//! ```sh
//! cargo test --locked -p tiamud-core typescript
//! ```
//!
//! Regenerate after changing a projected view, then review the diff:
//!
//! ```sh
//! TIAMUD_UPDATE_GENERATED_PROTOCOL=1 cargo test --locked -p tiamud-core typescript
//! ```

