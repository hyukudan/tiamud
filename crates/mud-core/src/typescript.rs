/// Prefixes the `type` line of a declaration (after any JSDoc) with `export`.
fn exported(declaration: &str) -> String {
    let mut output = String::with_capacity(declaration.len() + 8);
    let mut exported = false;
    for line in declaration.lines() {
        if !exported && line.starts_with("type ") {
            output.push_str("export ");
            exported = true;
        }
        output.push_str(line);
        output.push('\n');
    }
    assert!(exported, "declaration without a type line: {declaration}");
    output
}

fn render() -> String {
    // JSON numbers decode to JavaScript numbers; every projected integer is
    // bounded well below 2^53 by the server before it is serialized.
    let config = Config::new().with_large_int("number");
    let mut output = String::from(
        "// @generated by `cargo test -p tiamud-core typescript` from the tiamud-core view types.\n\
         // Do not edit by hand: run `TIAMUD_UPDATE_GENERATED_PROTOCOL=1 cargo test -p tiamud-core typescript`.\n\
         // These declarations describe the projections embedded in `tiamud.v1` frames;\n\
         // the browser still validates every inbound frame at runtime in `../protocol.ts`.\n",
    );
    for declaration in declarations(&config) {
        output.push('\n');
        output.push_str(&exported(&declaration));
    }
    output
}

#[test]
fn generated_typescript_is_current() {
    let path = generated_path();
    let rendered = render();
    if std::env::var_os(UPDATE_VARIABLE).is_some_and(|value| value == "1") {
        std::fs::create_dir_all(path.parent().expect("generated path has a parent"))
            .expect("create generated directory");
        std::fs::write(&path, &rendered).expect("write generated TypeScript");
        return;
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == rendered,
        "{} is stale; run `{UPDATE_VARIABLE}=1 cargo test --locked -p tiamud-core typescript` and review the diff",
        path.display()
    );
}
