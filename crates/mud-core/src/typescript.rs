const UPDATE_VARIABLE: &str = "TIAMUD_UPDATE_GENERATED_PROTOCOL";

fn generated_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../apps/web/src/lib/generated/core.ts")
}

